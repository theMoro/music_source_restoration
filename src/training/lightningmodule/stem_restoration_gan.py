"""
GAN fine-tuning pipeline for per-stem restoration models: takes the fine-tuned mixture
restoration generator (Apollo, src/models/apollo/apollo_wrapper.py, trained by
src/training/lightningmodule/mixture_restoration_gan.py::MixtureRestorationGANLightning) and fine-tunes
one copy per stem to map a separator's stem prediction (augmented) back to the clean, unaugmented
ground-truth stem.

Unlike MixtureRestorationGANLightning, there is no synthetic degradation pipeline here: pairs
come directly from src.data.stem_restoration_dataset.StemRestorationDataset, which reads
(separated_stem, clean_stem) file pairs generated by generate_inference_dataset_with_trainer
(src/train.py, see scripts/stem_restoration/generate_dataset.sh). Loss functions,
manual-optimization GAN training loop, and LR scheduling mirror MixtureRestorationGANLightning
exactly (multi-resolution STFT reconstruction loss + LSGAN spectral discriminator +
feature-matching loss); only the batch format and pair construction differ.
"""

import math
from typing import Optional, Tuple

import numpy as np
import torch
import lightning.pytorch as pl
import zimtohrli
from torchaudio.transforms import Spectrogram
from torchmetrics.functional.audio import signal_distortion_ratio

from src.utils import initialize_config
from src.training.loss.gan_loss import (
    MultiResolutionSTFTLoss,
    discriminator_loss_with_stats,
    generator_gan_loss,
    feature_matching_loss,
)
from src.training.loss.mel_spectrogram_loss import MultiResolutionMelLoss, ScaleInvariantMultiMelSNRLoss
from src.training.metrics.multi_mel_snr import multi_mel_snr_stereo_ct
from src.training.metrics.lsd import lsd_metric
from src.training.metrics.zimtohrli_distance import zimtohrli_distance

class StemRestorationGANLightning(pl.LightningModule):
    """
    Args:
        generator: module/main/args config for the restoration generator
            (src.models.apollo.ApolloWrapper). Set generator.args.ckpt_path to the mixture
            restoration checkpoint to fine-tune from.
        discriminator: module/main/args config for the spectral discriminator
            (src.models.frequency_discriminator.MultiFrequencyDiscriminator).
            Always initialized fresh (random init): only the generator's weights are extracted
            from ckpt_path (see ApolloWrapper._load_checkpoint).
        optimizer_g / optimizer_d: module/main/args config for the generator/discriminator
            optimizers (params filled in automatically).
        sampling_rate: expected audio sample rate (informational; comes from the dataset).
        stft_window_sizes / warmup_epochs / fm_loss_weight / gan_loss_weight / grad_clip_g /
        grad_clip_d / lr_scheduler_gamma / val_check_interval: identical semantics to
            MixtureRestorationGANLightning, see that module's docstring.
        mel_loss_weight: weight on MultiResolutionMelLoss (log-mel L1, same resolutions as the
            Multi-Mel-SNR eval metric), added to the generator loss alongside rec_loss (the
            linear-frequency multi-res STFT loss) so training optimizes directly in the domain
            the top-priority eval metric is measured in, rather than relying on rec_loss to
            correlate with it indirectly. Included during warmup too (it's a reconstruction loss,
            not adversarial).
        mel_snr_loss_weight: weight on ScaleInvariantMultiMelSNRLoss (src.training.loss.
            mel_spectrogram_loss), added to the generator loss alongside rec_loss/mel_loss.
            Unlike mel_loss_weight's L1 term, this optimizes the exact scale-invariant Mel-SNR
            formula val/mel_snr is scored with (see that class's docstring). Included during
            warmup too (a reconstruction-domain term, not adversarial). Default 0.0 -- this term
            is still computed and logged as train/mel_snr_loss even at weight 0 for visibility.
        train_discriminator: default True (unaffected existing behavior). When False, the
            discriminator is never trained or run at all -- no d_loss backward pass, no opt_d
            step, and the generator loss skips gan_loss/fm_loss entirely (same code path as
            warmup). Requires gan_loss_weight=0 and fm_loss_weight=0 (raises ValueError
            otherwise, since those terms would silently read an untrained discriminator).
            `self.discriminator` is still constructed (cheap: hidden_channels=8) so
            configure_optimizers/self.optimizers() keep returning the same (opt_g, opt_d) pair
            regardless of this flag. val/d_logits/... and val/d_logits_level_matched/... are also
            skipped in validation_step when this is False, for the same reason.
        accumulate_grad_batches: number of batches to accumulate gradients over before each
            optimizer step. Manual optimization (see automatic_optimization=False below) bypasses
            Trainer(accumulate_grad_batches=...), which only wraps the automatic optimization
            loop, so this must be set here (lightning_module.args.accumulate_grad_batches) rather
            than as a train.trainer.args override. Losses are still logged per micro-batch
            (unscaled); only the backward pass is divided by this value. Shared fallback default
            for accumulate_grad_batches_g/_d below when either is left unset.
        accumulate_grad_batches_g / accumulate_grad_batches_d: like accumulate_grad_batches, but
            set independently per optimizer; None (default) falls back to accumulate_grad_batches
            for that optimizer. D's forward/backward still run every micro-batch either way (only
            zero_grad/step are gated).
        num_val_audio_samples: number of fixed validation samples (batch_idx 0..N-1, batch item 0
            of each) to log as a degraded/enhanced/clean audio comparison to wandb every
            validation epoch (see _log_val_audio_comparison). val_dataloader is shuffle=False, so
            the same underlying samples are logged every epoch -- a listenable, apples-to-apples
            perceptual comparison alongside the scalar val/* metrics, since e.g. val/mel_snr can
            improve while artifacts a listener would flag (metallic/robotic texture, transient
            smearing) go undetected. Set to 0 to disable. No-ops if self.logger isn't a
            wandb-backed logger (e.g. local debugging runs with logger=None).
        ir_paths / lr_scheduler: accepted and discarded. main_helpers.initialize_components
            unconditionally injects ir_paths into every lightning_module's args, and Sacred's
            default_conf() unconditionally re-injects lr_scheduler into lightning_module.args as
            soon as any CLI `with` override touches a nested lightning_module.args.* key — see
            MixtureRestorationGANLightning's docstring for the full explanation. Neither is used
            here (no degradation pipeline, no separation-model-style LR schedule).
        n_sources: accepted and discarded (not stored/used, mirrors MixtureRestorationGANLightning).
            src/train.py::main() unconditionally reads lightning_module.args.n_sources to pick the
            `columns` list, which it then injects into the train/val dataset args as `columns`
            (see StemRestorationDataset, which also accepts and discards `columns`).
    """

    def __init__(
        self,
        generator: dict,
        discriminator: dict,
        optimizer_g: dict,
        optimizer_d: dict,
        sampling_rate: int = 48000,
        stft_window_sizes: Tuple[int, ...] = (512, 1024, 2048),
        warmup_epochs: int = 0,
        mel_loss_weight: float = 1.0,
        mel_snr_loss_weight: float = 0.0,
        fm_loss_weight: float = 1.0,
        gan_loss_weight: float = 1.0,
        train_discriminator: bool = True,
        grad_clip_g: float = 5.0,
        grad_clip_d: float = 5.0,
        lr_scheduler_gamma: float = 0.98,
        val_check_interval: float = 1.0,
        accumulate_grad_batches: int = 1,
        accumulate_grad_batches_g: Optional[int] = None,
        accumulate_grad_batches_d: Optional[int] = None,
        num_val_audio_samples: int = 4,
        ir_paths=None,
        lr_scheduler: Optional[dict] = None,
        n_sources: int = 9,
    ):
        super().__init__()
        self.automatic_optimization = False

        self.sampling_rate = int(sampling_rate)
        self.warmup_epochs = int(warmup_epochs)
        self.mel_loss_weight = float(mel_loss_weight)
        self.mel_snr_loss_weight = float(mel_snr_loss_weight)
        self.fm_loss_weight = float(fm_loss_weight)
        self.gan_loss_weight = float(gan_loss_weight)
        self.train_discriminator = bool(train_discriminator)
        if not self.train_discriminator and (self.gan_loss_weight != 0.0 or self.fm_loss_weight != 0.0):
            raise ValueError(
                "train_discriminator=False requires gan_loss_weight=0 and fm_loss_weight=0 -- both "
                "read the discriminator, which train_discriminator=False never runs."
            )
        self.grad_clip_g = float(grad_clip_g)
        self.grad_clip_d = float(grad_clip_d)
        self.lr_scheduler_gamma = float(lr_scheduler_gamma)
        self.val_check_interval = float(val_check_interval)
        self.accumulate_grad_batches = int(accumulate_grad_batches)
        self.accumulate_grad_batches_g = (
            int(accumulate_grad_batches_g) if accumulate_grad_batches_g is not None else self.accumulate_grad_batches
        )
        self.accumulate_grad_batches_d = (
            int(accumulate_grad_batches_d) if accumulate_grad_batches_d is not None else self.accumulate_grad_batches
        )
        self.num_val_audio_samples = int(num_val_audio_samples)
        # Counts opt_d.step() calls (not micro-batches); val/d_logits is only logged once D has
        # taken at least one step (see validation_step).
        self._d_opt_step_count = 0

        self.generator_config = generator
        self.generator = initialize_config(self.generator_config)

        self.discriminator_config = discriminator
        self.discriminator = initialize_config(self.discriminator_config)

        self.optimizer_g_config = optimizer_g
        self.optimizer_d_config = optimizer_d

        self.rec_loss_fn = MultiResolutionSTFTLoss(window_sizes=stft_window_sizes)
        self.mel_loss_fn = MultiResolutionMelLoss(sample_rate=self.sampling_rate)
        self.mel_snr_loss_fn = ScaleInvariantMultiMelSNRLoss(sample_rate=self.sampling_rate)

        # Used only for val/lsd, which needs complex STFT tensors (mirrors Hachimi's self.spec).
        self.lsd_spec = Spectrogram(n_fft=1024, win_length=1024, hop_length=512, power=None)

        # Non-differentiable (CPU, numpy-backed) -- val/zimtohrli logging only, never a loss term.
        try:
            self._zimt_calculator = zimtohrli.Pyohrli()
        except Exception as e:
            print(f"Warning: failed to initialize Zimtohrli backend ({e}); val/zimtohrli will be skipped.")
            self._zimt_calculator = None

    # ------------------------------------------------------------------
    # Lightning hooks
    # ------------------------------------------------------------------

    def forward(self, x):
        return self.generator(x)

    def training_step(self, batch, batch_idx):
        opt_g, opt_d = self.optimizers()

        degraded = batch['input']  # [B, C, T] separator prediction (augmented)
        clean = batch['target']    # [B, C, T] raw ground-truth stem

        enhanced = self.generator({'mixture': degraded})['mixture']

        length = min(enhanced.shape[-1], clean.shape[-1])
        enhanced = enhanced[..., :length]
        clean = clean[..., :length]

        is_warmup = self.current_epoch < self.warmup_epochs
        # Decoupled per-optimizer -- see accumulate_grad_batches_g/_d docstring. Each optimizer's
        # zero_grad/step is gated independently so accumulate_grad_batches_d can be swept without
        # also changing how often opt_g steps.
        d_is_accum_start = batch_idx % self.accumulate_grad_batches_d == 0
        d_is_accum_end = ((batch_idx + 1) % self.accumulate_grad_batches_d == 0) or self.trainer.is_last_batch
        g_is_accum_start = batch_idx % self.accumulate_grad_batches_g == 0
        g_is_accum_end = ((batch_idx + 1) % self.accumulate_grad_batches_g == 0) or self.trainer.is_last_batch

        d_grad_norm = torch.tensor(0.0, device=self.device)
        d_grad_norm_postclip = torch.tensor(0.0, device=self.device)
        d_param_update_norm = torch.tensor(0.0, device=self.device)
        d_grad_clipped = None
        if not is_warmup and self.train_discriminator:
            if d_is_accum_start:
                opt_d.zero_grad()
            fake_for_d = enhanced.detach()
            d_loss, d_loss_real, d_loss_fake, d_stats = discriminator_loss_with_stats(
                self.discriminator, clean, fake_for_d
            )
            self.manual_backward(d_loss / self.accumulate_grad_batches_d)
            if d_is_accum_end:
                d_grad_norm = torch.nn.utils.clip_grad_norm_(self.discriminator.parameters(), self.grad_clip_d)
                d_grad_clipped = float(d_grad_norm > self.grad_clip_d)
                d_grad_norm_postclip = torch.sqrt(sum(
                    p.grad.detach().pow(2).sum() for p in self.discriminator.parameters() if p.grad is not None
                ))
                d_params_before = [p.detach().clone() for p in self.discriminator.parameters()]
                opt_d.step()
                self._d_opt_step_count += 1
                d_param_update_norm = torch.sqrt(sum(
                    ((p.detach() - before) ** 2).sum()
                    for p, before in zip(self.discriminator.parameters(), d_params_before)
                ))
        else:
            d_loss = torch.tensor(0.0, device=self.device)
            d_loss_real = torch.tensor(0.0, device=self.device)
            d_loss_fake = torch.tensor(0.0, device=self.device)
            d_stats = None

        g_grad_norm = torch.tensor(0.0, device=self.device)
        if g_is_accum_start:
            opt_g.zero_grad()
        rec_loss = self.rec_loss_fn(enhanced, clean)
        mel_loss = self.mel_loss_fn(enhanced, clean)
        mel_snr_loss = self.mel_snr_loss_fn(enhanced, clean)
        base_g_loss = (
            rec_loss
            + self.mel_loss_weight * mel_loss
            + self.mel_snr_loss_weight * mel_snr_loss
        )

        if is_warmup or not self.train_discriminator:
            g_loss = base_g_loss
            fm_loss = torch.tensor(0.0, device=self.device)
            gan_loss = torch.tensor(0.0, device=self.device)
        else:
            gan_loss, fake_features, real_features = generator_gan_loss(self.discriminator, enhanced, clean)
            fm_loss = feature_matching_loss(fake_features, real_features)
            g_loss = (
                base_g_loss
                + self.fm_loss_weight * fm_loss
                + self.gan_loss_weight * gan_loss
            )

        self.manual_backward(g_loss / self.accumulate_grad_batches_g)
        if g_is_accum_end:
            g_grad_norm = torch.nn.utils.clip_grad_norm_(self.generator.parameters(), self.grad_clip_g)
            opt_g.step()

        batch_size = clean.shape[0]
        self.log('train/g_loss', g_loss, prog_bar=True, batch_size=batch_size)
        self.log('train/d_loss', d_loss, prog_bar=True, batch_size=batch_size)
        self.log('train/rec_loss', rec_loss, batch_size=batch_size)
        self.log('train/mel_loss', mel_loss, batch_size=batch_size)
        self.log('train/mel_snr_loss', mel_snr_loss, batch_size=batch_size)
        self.log('train/mel_snr_loss_weighted', self.mel_snr_loss_weight * mel_snr_loss, batch_size=batch_size)
        self.log('train/fm_loss', fm_loss, batch_size=batch_size)
        self.log('train/gan_loss', gan_loss, batch_size=batch_size)
        # Split real/fake discriminator loss terms -- a collapsing/diverging d_loss alone
        # doesn't say whether D stopped separating real from fake (both terms shrink together)
        # or overpowered G (loss_fake shrinks while loss_real grows), which call for opposite
        # fixes (warm up longer / lower lr_d vs. raise gan_loss_weight / lr_g).
        self.log('train/d_loss_real', d_loss_real, batch_size=batch_size)
        self.log('train/d_loss_fake', d_loss_fake, batch_size=batch_size)

        # Fraction-of-D-optimizer-steps-that-clipped and the L2 norm of the actual parameter
        # delta opt_d.step() applied (as opposed to d_grad_norm below, which is the
        # *pre-clipping* gradient norm) -- only meaningful at accum-end steps where opt_d.step()
        # actually ran, so only logged then (wandb averages over however many such events land in
        # a logging window, giving a true "fraction of update steps" rather than "fraction of
        # micro-batches", most of which don't call opt_d.step() under accumulation).
        if d_grad_clipped is not None:
            self.log('train/d_grad_clip_fraction', d_grad_clipped, batch_size=batch_size)
            self.log('train/d_param_update_norm', d_param_update_norm, batch_size=batch_size)

        # Gradient norms (pre-clip, from clip_grad_norm_'s return value) for both optimizers --
        # 0.0 on warmup/non-accum-end steps where the corresponding backward/clip didn't run this
        # step. A norm consistently pinned at grad_clip_g/grad_clip_d indicates clipping is doing
        # real work (potentially masking an LR that's too high); one that collapses toward 0
        # indicates vanishing gradients (e.g. a saturated discriminator for train/g_grad_norm).
        self.log('train/d_grad_norm', d_grad_norm, batch_size=batch_size)
        self.log('train/g_grad_norm', g_grad_norm, batch_size=batch_size)
        # Aliases of d_grad_norm (pre-clip) and its post-clip counterpart -- only meaningful (nonzero) at accum-end steps,
        # same caveat as train/d_grad_norm above.
        self.log('train/d_total_grad_norm_preclip', d_grad_norm, batch_size=batch_size)
        self.log('train/d_total_grad_norm_postclip', d_grad_norm_postclip, batch_size=batch_size)

        # Per-sub-discriminator (per STFT window size) diagnostics on the raw D(real)/D(fake)
        # logits -- see discriminator_loss_with_stats. Only available on non-warmup steps that
        # actually ran the discriminator forward pass above.
        if d_stats is not None:
            self._log_d_stats('train/d_logits', d_stats, batch_size)

    def _log_d_stats(self, prefix: str, d_stats, batch_size: int, sync_dist: bool = False):
        """Logs discriminator_loss_with_stats' per-sub-discriminator stats dicts under
        f'{prefix}/win{window_size}/{key}' for each (window_size, stats-dict) pair, skipping any
        None values (e.g. gap_median when real_logit/fake_logit shapes mismatched -- shouldn't
        happen in practice here, but _binary_discrimination_stats degrades gracefully rather than
        raising). Shared between training_step's train/d_logits/... and validation_step's
        val/d_logits/... / val/d_logits_level_matched/... so both log the identical metric set --
        see gan_loss._binary_discrimination_stats for what each field means:
        real_mean/real_std/fake_mean/fake_std are the raw per-logit-tensor moments; the rest
        (gap_median/gap_p10/gap_p90/frac_real_gt_fake/auc/balanced_accuracy) directly answer "is D
        discriminating?" in a way aggregate means/losses alone can hide (see the module and
        _binary_discrimination_stats docstrings).
        """
        for window_size, s in zip(self.discriminator.window, d_stats):
            win_prefix = f'{prefix}/win{window_size}'
            for key, value in s.items():
                if value is not None:
                    self.log(f'{win_prefix}/{key}', value, batch_size=batch_size, sync_dist=sync_dist)

    def on_train_batch_end(self, outputs, batch, batch_idx):
        total_batches = self.trainer.num_training_batches
        step_interval = max(1, int(total_batches * self.val_check_interval))
        if (batch_idx + 1) % step_interval == 0:
            sch_g, sch_d = self.lr_schedulers()
            sch_g.step()
            if self.current_epoch >= self.warmup_epochs:
                sch_d.step()

    def validation_step(self, batch, batch_idx):
        degraded = batch['input']
        clean = batch['target']
        with torch.no_grad():
            enhanced = self.generator({'mixture': degraded})['mixture']

        length = min(enhanced.shape[-1], clean.shape[-1])
        enhanced = enhanced[..., :length]
        clean = clean[..., :length]
        degraded = degraded[..., :length]

        if batch_idx < self.num_val_audio_samples:
            self._log_val_audio_comparison(batch_idx, degraded, enhanced, clean)

        rec_loss = self.rec_loss_fn(enhanced, clean)
        mel_loss = self.mel_loss_fn(enhanced, clean)

        batch_size = clean.shape[0]
        mel_snrs, sdrs, lsds, zimts = [], [], [], []
        for b in range(batch_size):
            mel_snrs.append(multi_mel_snr_stereo_ct(enhanced[b], clean[b], self.sampling_rate))
            if clean[b].abs().max() > 1e-8:
                sdrs.append(signal_distortion_ratio(enhanced[b], clean[b]).mean().item())
            pred_stft = self.lsd_spec(enhanced[b])
            target_stft = self.lsd_spec(clean[b])
            lsds.append(lsd_metric(pred_stft, target_stft).item())
            zimts.append(zimtohrli_distance(self._zimt_calculator, enhanced[b], clean[b]))

        self.log('val/loss', rec_loss, prog_bar=True, batch_size=batch_size, sync_dist=True)
        self.log('val/mel_loss', mel_loss, batch_size=batch_size, sync_dist=True)
        # Checkpoint selection (see the `checkpoint` callback config) still monitors val/mel_snr
        # only -- val/zimtohrli is logged for visibility (and for manually comparing candidate
        # checkpoints against Zimtohrli/FAD-CLAP before picking a final one), not wired into
        # ModelCheckpoint's `monitor`.
        self.log('val/mel_snr', float(np.mean(mel_snrs)), prog_bar=True, batch_size=batch_size, sync_dist=True)
        if sdrs:
            self.log('val/sdr', float(np.mean(sdrs)), batch_size=batch_size, sync_dist=True)
        self.log('val/lsd', float(np.mean(lsds)), batch_size=batch_size, sync_dist=True)
        finite_zimts = [z for z in zimts if math.isfinite(z)]
        if finite_zimts:
            self.log('val/zimtohrli', float(np.mean(finite_zimts)), prog_bar=True, batch_size=batch_size, sync_dist=True)

        # Discriminator diagnostics on this held-out batch -- unlike train/d_logits/..., this
        # isn't affected by the accum_d cadence sweep (runs on every val batch regardless) and,
        # since val_dataloader is shuffle=False, gives a fixed, reproducible set of real/fake
        # pairs to track discrimination quality (AUC/balanced accuracy/gap, see
        # gan_loss._binary_discrimination_stats) epoch over epoch. Skipped when
        # train_discriminator=False -- D is never trained in that mode, so its logits are just
        # noise from an untrained/frozen-at-init network -- and also for src/train.py's step-zero
        # validation pass (before trainer.fit() starts, i.e. self._d_opt_step_count still 0): D is
        # randomly-initialized and can produce wildly unstable logits on its very first forward
        # pass, which would otherwise corrupt that epoch's logged gap_mean/gap_median/auc with a
        # meaningless outlier. Ported from MixtureRestorationGANLightning's validation_step.
        if self.train_discriminator and self._d_opt_step_count > 0:
            with torch.no_grad():
                _, _, _, d_stats = discriminator_loss_with_stats(self.discriminator, clean, enhanced)
            self._log_d_stats('val/d_logits', d_stats, batch_size, sync_dist=True)

            # Level-matched variant: force the fake's per-sample RMS to match the real's before
            # feeding both to D, regardless of this run's discriminator.normalize_power setting --
            # isolates "is D still discriminating once an overall loudness/gain mismatch can no
            # longer be used as a shortcut cue" (see MultiFrequencyDiscriminator's normalize_power
            # docstring and the no-power-norm ablation results that motivated this) from whatever
            # normalize_power happens to be configured for this run. A gap that only shows up in
            # val/d_logits/... (raw) but disappears here indicates D was mostly keying off loudness;
            # one that persists here indicates a level-independent cue.
            eps = torch.finfo(enhanced.dtype).eps
            real_rms = clean.pow(2).mean(dim=(1, 2), keepdim=True).sqrt().clamp_min(eps)
            fake_rms = enhanced.pow(2).mean(dim=(1, 2), keepdim=True).sqrt().clamp_min(eps)
            level_matched_fake = enhanced * (real_rms / fake_rms)
            with torch.no_grad():
                _, _, _, d_stats_level_matched = discriminator_loss_with_stats(self.discriminator, clean, level_matched_fake)
            self._log_d_stats('val/d_logits_level_matched', d_stats_level_matched, batch_size, sync_dist=True)

    def _log_val_audio_comparison(
        self, sample_idx: int, degraded: torch.Tensor, enhanced: torch.Tensor, clean: torch.Tensor
    ):
        """Logs one fixed validation sample's degraded input / model output / clean target as
        listenable audio to wandb, so restoration quality can be spot-checked by ear against the
        exact same clip every validation epoch (see num_val_audio_samples). Best-effort: never
        raises, since a logging failure here shouldn't crash validation.
        """
        logger = self.logger
        if logger is None or not hasattr(logger, 'experiment') or not getattr(self.trainer, 'is_global_zero', True):
            return
        try:
            import wandb
            audio = {
                'degraded': degraded[0],
                'enhanced': enhanced[0],
                'clean': clean[0],
            }
            # No explicit step= here: under manual optimization self.global_step doesn't reliably
            # track the step WandbLogger has already advanced to via this same training_step's
            # regular self.log(...) calls, so asserting a stale/lower step gets silently dropped
            # ("Tried to log to step N that is less than the current step" wandb warning). Omitting
            # step lets wandb use its own auto-incrementing counter instead.
            logger.experiment.log({
                f'val_audio/sample_{sample_idx}/{name}': wandb.Audio(
                    wav.detach().float().cpu().numpy().T, sample_rate=self.sampling_rate
                )
                for name, wav in audio.items()
            })
        except Exception as e:
            print(f"Warning: failed to log val audio comparison for sample {sample_idx} ({e}); skipping.")

    def configure_optimizers(self):
        opt_g_config = dict(self.optimizer_g_config)
        # Only trainable params -- generator.args.freeze_band_split/num_frozen_bsnet_layers (see
        # src.models.apollo.apollo_wrapper.ApolloWrapper) can leave some of self.generator frozen.
        trainable_g_params = [p for p in self.generator.parameters() if p.requires_grad]
        opt_g_config['args'] = {**opt_g_config.get('args', {}), 'params': trainable_g_params}
        opt_g = initialize_config(opt_g_config)

        opt_d_config = dict(self.optimizer_d_config)
        opt_d_config['args'] = {**opt_d_config.get('args', {}), 'params': list(self.discriminator.parameters())}
        opt_d = initialize_config(opt_d_config)

        sch_g = torch.optim.lr_scheduler.ExponentialLR(opt_g, gamma=self.lr_scheduler_gamma)
        sch_d = torch.optim.lr_scheduler.ExponentialLR(opt_d, gamma=self.lr_scheduler_gamma)

        return [opt_g, opt_d], [sch_g, sch_d]